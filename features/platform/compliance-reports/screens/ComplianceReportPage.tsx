import Link from 'next/link';
import { notFound } from 'next/navigation';
import { ArrowUpRight } from 'lucide-react';
import type { ReactNode } from 'react';

import { PageContainer } from '@/features/dashboard/components/PageContainer';
import { Alert, AlertDescription } from '@/components/ui/alert';
import { Dot, ListBand, PageTitle, SectionTitle, buttonClass } from '@/features/platform/components/vape-ui';
import { cn } from '@/lib/utils';
import { REPORT_STATUS_LABELS, REPORT_TYPE_LABELS } from '@/features/keystone/regulated/labels';
import { outLinkClass } from '@/features/platform/compliance-ledger/components/LinkTrack';
import { ORDERS_PATH, REPORTS_PATH, dateTime, eventLabel, label, periodText, reasonLabel, shortId, stateTone } from '@/features/platform/compliance-ledger/lib/format';
import { getReport } from '../actions/reports';
import { RecordSubmissionButton } from '../components/ReportSheets';

const breadcrumbs = (id: string) => [
  { type: 'link' as const, label: 'Dashboard', href: '/dashboard' },
  { type: 'page' as const, label: 'Platform' },
  { type: 'link' as const, label: 'Compliance reports', href: REPORTS_PATH },
  { type: 'page' as const, label: `Report ${shortId(id)}` },
];

const SUBMITTABLE = new Set(['generated', 'reviewed', 'submitted']);
const Mono = ({ children }: { children: ReactNode }) => <span className="break-all font-mono text-xs tabular-nums">{children}</span>;
const person = (user: { name: string | null; email: string | null } | null) => user?.name || user?.email || '';

export async function ComplianceReportPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const response = await getReport(id);

  if (!response.success) {
    return (
      <PageContainer title="Report" header={<PageTitle title="Report" />} breadcrumbs={breadcrumbs(id)}>
        <div className="px-4 pb-24 sm:pb-10 md:px-6">
          <Alert variant="destructive"><AlertDescription>{response.error}</AlertDescription></Alert>
        </div>
      </PageContainer>
    );
  }
  if (!response.data) notFound();

  const { report, receipt, events, canManage } = response.data;
  const sources = (Array.isArray(report.sourceTransactionIds) ? report.sourceTransactionIds : []).filter(
    (value): value is string => typeof value === 'string',
  );
  const orderIds = [...new Set(sources)];
  const policies = (Array.isArray(report.policyVersions) ? report.policyVersions : []).map(String);
  const title = `${label(REPORT_TYPE_LABELS, report.reportType)}${report.jurisdiction?.code ? ` · ${report.jurisdiction.code}` : ''}`;

  const header = (
    <PageTitle
      title={title}
      tone={stateTone(report.status)}
      state={label(REPORT_STATUS_LABELS, report.status)}
      meta={<span className="font-mono tabular-nums">{periodText(report.periodStartsAt, report.periodEndsAt)}</span>}
    />
  );

  const facts: Array<[string, ReactNode]> = [
    ['Merchant', report.merchantProfile?.legalName],
    ['Jurisdiction', report.jurisdiction ? `${report.jurisdiction.code} · ${report.jurisdiction.name}` : null],
    ['Generated', <Mono key="g">{dateTime(report.generatedAt)}</Mono>],
    ['Generated by', person(report.generatedBy)],
    ['Submitted', report.submittedAt ? <Mono>{dateTime(report.submittedAt)}</Mono> : 'Not submitted'],
    ['Submitted by', person(report.submittedBy)],
    ['Filing receipt', canManage ? (receipt ? <Mono>{receipt}</Mono> : 'None') : null],
    ['Content SHA-256', <Mono key="d">{report.contentDigest}</Mono>],
    ['Supersedes', report.supersedes ? (
      <Link href={`${REPORTS_PATH}/${report.supersedes.id}`} className={outLinkClass}>
        {label(REPORT_TYPE_LABELS, report.supersedes.reportType)} · {dateTime(report.supersedes.generatedAt)}
        <ArrowUpRight className="size-3" />
      </Link>
    ) : null],
  ];

  return (
    <PageContainer title={title} header={header} breadcrumbs={breadcrumbs(id)}>
      <div className="space-y-8 px-4 pb-24 sm:pb-10 md:px-6">
        {canManage && SUBMITTABLE.has(report.status) && (
          <div className="flex flex-wrap gap-2">
            <RecordSubmissionButton reportId={report.id} className={cn(buttonClass.base, buttonClass.primary)} />
          </div>
        )}

        <section className="grid gap-8 lg:grid-cols-2">
          <div>
            <SectionTitle>Report</SectionTitle>
            <ListBand>
              {facts.filter(([, value]) => value !== null && value !== undefined && value !== '').map(([name, value]) => (
                <div key={name} className="grid gap-1 px-4 py-2.5 sm:grid-cols-[9rem_minmax(0,1fr)] sm:gap-4">
                  <dt className="text-xs text-muted-foreground">{name}</dt>
                  <dd className="min-w-0 break-words text-sm text-foreground">{value}</dd>
                </div>
              ))}
            </ListBand>
          </div>
          <div className="space-y-8">
            <div>
              <SectionTitle meta={policies.length}>Policy versions</SectionTitle>
              <ListBand>
                {policies.length === 0 && <div className="px-4 py-3 text-sm text-muted-foreground">None</div>}
                {policies.map(policy => (
                  <div key={policy} className="px-4 py-2.5"><Mono>{policy}</Mono></div>
                ))}
              </ListBand>
            </div>
            <div>
              <SectionTitle meta={events.length}>Events</SectionTitle>
              <ListBand>
                {events.length === 0 && <div className="px-4 py-3 text-sm text-muted-foreground">No events</div>}
                {events.map(event => (
                  <div key={event.id} className="flex flex-wrap items-baseline justify-between gap-x-4 gap-y-1 px-4 py-2.5">
                    <span className="min-w-0">
                      <span className="flex items-baseline gap-2.5 text-sm text-foreground">
                        <Dot tone="muted" />
                        {eventLabel(event.eventType)}
                      </span>
                      {event.reasonCode && <span className="block pl-[1.125rem] text-xs text-muted-foreground">{reasonLabel(event.reasonCode)}</span>}
                    </span>
                    <span className="font-mono text-xs tabular-nums text-muted-foreground">{dateTime(event.occurredAt)}</span>
                  </div>
                ))}
              </ListBand>
            </div>
          </div>
        </section>

        <section>
          <SectionTitle meta={orderIds.length}>Orders</SectionTitle>
          <ListBand>
            {orderIds.length === 0 && <div className="px-4 py-3 text-sm text-muted-foreground">No orders in this period</div>}
            {orderIds.slice(0, 100).map(orderId => (
              <div key={orderId} className="flex items-baseline justify-between gap-4 px-4 py-2.5">
                <Mono>{orderId}</Mono>
                <Link href={`${ORDERS_PATH}/${orderId}`} className={outLinkClass}>
                  Order
                  <ArrowUpRight className="size-3" />
                </Link>
              </div>
            ))}
          </ListBand>
        </section>
      </div>
    </PageContainer>
  );
}

export default ComplianceReportPage;
